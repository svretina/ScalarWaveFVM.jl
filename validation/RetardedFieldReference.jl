module RetardedFieldReference

export TrajectoryHistory, trajectory_state, retarded_scalar_1d,
       independent_puncture_1d, zero_remainder_homogeneous_1d,
       exact_remainder_1d, cell_average_exact_remainder_1d

struct TrajectoryHistory{TT,TZ,TV,TTAU}
    t::TT
    z::TZ
    v::TV
    τ::TTAU
end

function TrajectoryHistory(t, z, v, τ)
    n = length(t)
    n >= 2 || throw(ArgumentError("trajectory requires at least two samples"))
    length(z) == n && length(v) == n && length(τ) == n ||
        throw(DimensionMismatch("trajectory arrays must have equal lengths"))
    all(diff(t) .> 0) || throw(ArgumentError("trajectory times must increase"))
    maximum(abs, v) < 1 || throw(ArgumentError("trajectory must be timelike"))
    return TrajectoryHistory{typeof(t),typeof(z),typeof(v),typeof(τ)}(t, z, v, τ)
end

@inline function _hermite_value(y0, y1, dy0, dy1, h, s)
    h00 = 2s^3 - 3s^2 + 1
    h10 = s^3 - 2s^2 + s
    h01 = -2s^3 + 3s^2
    h11 = s^3 - s^2
    return h00 * y0 + h10 * h * dy0 + h01 * y1 + h11 * h * dy1
end

@inline function _hermite_derivative(y0, y1, dy0, dy1, h, s)
    return ((6s^2 - 6s) * y0 + (3s^2 - 4s + 1) * h * dy0 +
            (-6s^2 + 6s) * y1 + (3s^2 - 2s) * h * dy1) / h
end

"""Interpolate `(z,v,τ)` without using any production field routines."""
function trajectory_state(history::TrajectoryHistory, time)
    first(history.t) <= time <= last(history.t) ||
        throw(DomainError(time, "time lies outside the stored trajectory"))
    i = clamp(searchsortedlast(history.t, time), 1, length(history.t) - 1)
    h = history.t[i + 1] - history.t[i]
    s = (time - history.t[i]) / h
    z = _hermite_value(history.z[i], history.z[i + 1],
                       history.v[i], history.v[i + 1], h, s)
    v = _hermite_derivative(history.z[i], history.z[i + 1],
                            history.v[i], history.v[i + 1], h, s)
    dτ0 = sqrt(1 - history.v[i]^2)
    dτ1 = sqrt(1 - history.v[i + 1]^2)
    τ = _hermite_value(history.τ[i], history.τ[i + 1], dτ0, dτ1, h, s)
    return (; z, v, τ)
end

"""Exact switched-on retarded field generated by the interpolated worldline."""
function retarded_scalar_1d(history::TrajectoryHistory, time, x, q;
                            iterations=64)
    t0 = first(history.t)
    initial = trajectory_state(history, t0)
    T = promote_type(typeof(float(time)), typeof(float(x)), typeof(float(q)))
    if time <= t0 || abs(x - initial.z) >= time - t0
        return (Φ=zero(T), Π=zero(T), Ψ=zero(T), tret=nothing)
    end

    current = trajectory_state(history, time)
    n = x >= current.z ? one(T) : -one(T)
    target = time - n * x
    null_coordinate(s) = s - n * trajectory_state(history, s).z - target
    lo, hi = t0, time
    for _ in 1:iterations
        mid = (lo + hi) / 2
        if null_coordinate(mid) < 0
            lo = mid
        else
            hi = mid
        end
    end

    tret = (lo + hi) / 2
    retarded = trajectory_state(history, tret)
    inverse_gamma = sqrt(1 - retarded.v^2)
    denominator = 1 - n * retarded.v
    return (Φ=-0.5 * q * (retarded.τ - initial.τ),
            Π=-0.5 * q * inverse_gamma / denominator,
            Ψ=0.5 * q * n * inverse_gamma / denominator,
            tret)
end

"""Independent evaluator for the retarded-matched analytical puncture."""
@inline function independent_puncture_1d(x, z, v, q, τ)
    r = x - z
    n = sign(r)
    gamma = inv(sqrt(1 - v^2))
    return (Φ=0.5 * q * (gamma * (abs(r) + v * r) - τ),
            Π=-0.5 * q * gamma * (1 + v * n),
            Ψ=0.5 * q * gamma * (n + v))
end

"""
Exact d'Alembert correction when the initial numerical remainder is zero.

The initial total field is the puncture, while the switched-on retarded field
vanishes.  This function propagates their initial difference independently.
"""
function zero_remainder_homogeneous_1d(history::TrajectoryHistory, time, x, q)
    t0 = first(history.t)
    initial = trajectory_state(history, t0)
    dt = time - t0
    dt >= 0 || throw(DomainError(time, "time precedes the initial data"))
    gamma = inv(sqrt(1 - initial.v^2))

    f(y) = 0.5 * q * (gamma *
           (abs(y - initial.z) + initial.v * (y - initial.z)) - initial.τ)
    fp(y) = 0.5 * q * gamma * (sign(y - initial.z) + initial.v)
    g(y) = -0.5 * q * gamma * (1 + initial.v * sign(y - initial.z))
    G(y) = -0.5 * q * gamma * (y + initial.v * abs(y - initial.z))

    left, right = x - dt, x + dt
    return (Φ=0.5 * (f(left) + f(right) + G(right) - G(left)),
            Π=0.5 * (-fp(left) + fp(right) + g(left) + g(right)),
            Ψ=0.5 * (fp(left) + fp(right) + g(right) - g(left)))
end

"""Exact remainder matching a zero-remainder numerical initial state."""
function exact_remainder_1d(history::TrajectoryHistory, time, x, q)
    current = trajectory_state(history, time)
    retarded = retarded_scalar_1d(history, time, x, q)
    homogeneous = zero_remainder_homogeneous_1d(history, time, x, q)
    puncture = independent_puncture_1d(x, current.z, current.v, q, current.τ)
    return (Φ=retarded.Φ + homogeneous.Φ - puncture.Φ,
            Π=retarded.Π + homogeneous.Π - puncture.Π,
            Ψ=retarded.Ψ + homogeneous.Ψ - puncture.Ψ)
end

const GL8_NODES = (-0.9602898564975363, -0.7966664774136267,
                   -0.5255324099163290, -0.1834346424956498,
                    0.1834346424956498,  0.5255324099163290,
                    0.7966664774136267,  0.9602898564975363)
const GL8_WEIGHTS = (0.1012285362903763, 0.2223810344533745,
                     0.3137066458778873, 0.3626837833783620,
                     0.3626837833783620, 0.3137066458778873,
                     0.2223810344533745, 0.1012285362903763)

"""Eight-point cell average, split at the particle and causal fronts."""
function cell_average_exact_remainder_1d(history::TrajectoryHistory,
                                         time, center, width, q)
    left, right = center - width / 2, center + width / 2
    t0 = first(history.t)
    initial = trajectory_state(history, t0)
    current = trajectory_state(history, time)
    breaks = [left, right]
    for point in (current.z, initial.z - (time - t0), initial.z + (time - t0))
        left < point < right && push!(breaks, point)
    end
    sort!(breaks)

    integral_Φ = zero(float(center))
    integral_Π = zero(float(center))
    integral_Ψ = zero(float(center))
    for i in 1:(length(breaks) - 1)
        a, b = breaks[i], breaks[i + 1]
        midpoint, halfwidth = (a + b) / 2, (b - a) / 2
        for (node, weight) in zip(GL8_NODES, GL8_WEIGHTS)
            value = exact_remainder_1d(history, time,
                                       midpoint + halfwidth * node, q)
            integral_Φ += halfwidth * weight * value.Φ
            integral_Π += halfwidth * weight * value.Π
            integral_Ψ += halfwidth * weight * value.Ψ
        end
    end
    return (Φ=integral_Φ / width,
            Π=integral_Π / width,
            Ψ=integral_Ψ / width)
end

end
